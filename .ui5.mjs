import { chromium } from 'playwright'
const base = 'http://localhost:3000'
let failures = 0
const check = (n, ok, d = '') => { if (!ok) failures++; console.log((ok ? 'PASS ' : 'FAIL ') + n + (ok ? '' : ' ' + d)) }
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' })
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage()
page.setDefaultTimeout(180000)
const errors = []; page.on('pageerror', (e) => errors.push(e.message.split('\n')[0]))
await page.goto(base + '/en/museum/6ad6d5253ac2699868136b04/navigation?at=6ad6d5243ac2699868136ad5')
await page.getByText('Free visit').waitFor()
check('free navigation header names the museum', await page.getByRole('heading', { name: 'Museo Galileo' }).isVisible())
check('no tour progress in free mode', (await page.getByLabel('Tour progress').count()) === 0)
await page.waitForTimeout(2500)
await page.screenshot({ path: process.argv[2] + '/free-nav.png' })
await page.getByRole('button', { name: 'Search' }).click()
const tourPill = page.getByRole('button', { name: /Galileo: strumenti e scoperte/ })
await tourPill.waitFor()
await page.screenshot({ path: process.argv[2] + '/free-spotlight.png' })
check('empty Spotlight offers the museum tours', await page.getByText('Tours in this museum').isVisible())
await tourPill.click()
await page.waitForURL(/\/en\/tour\/6ad6d5253ac2699868136b6f\/navigation\/0/)
check('starting a tour keeps the confirmed position', new URL(page.url()).searchParams.get('at') === '6ad6d5243ac2699868136ad5', page.url())
await page.goto(base + '/en/museum/6ad6d5253ac2699868136b04/navigation/content/6ad6d5243ac2699868136ab3?to=6ad6d5243ac2699868136ad5')
const dialog = page.getByRole('dialog')
await dialog.waitFor()
check('content opens in a modal over the free map', (await dialog.innerText()).includes('Galileo e la nascita'))
await page.waitForTimeout(1500)
await page.screenshot({ path: process.argv[2] + '/free-content.png' })
await page.getByRole('button', { name: 'Close' }).click()
await page.waitForURL((u) => u.pathname === '/en/museum/6ad6d5253ac2699868136b04/navigation')
check('closing returns to the free map with state', new URL(page.url()).searchParams.get('to') === '6ad6d5243ac2699868136ad5', page.url())
await page.goto(base + '/en/museum/6ad6d5253ac2699868136b04/navigation?at=6ad6d5243ac2699868136ad5')
await page.getByText('Free visit').waitFor()
await page.getByRole('button', { name: 'Search' }).click()
await page.getByPlaceholder(/Search tours, objects/).fill('Cannocchiale')
await page.getByRole('button', { name: /Cannocchiale galileiano/ }).first().click()
await page.waitForURL(/\/navigation\/object\//)
check('Spotlight object opens in free modal', /\/museum\/6ad6d5253ac2699868136b04\/navigation\/object\/6ad6d5243ac2699868136ad5/.test(page.url()), page.url())
await page.getByRole('button', { name: 'Navigate here' }).click()
await page.waitForURL((u) => u.searchParams.get('to') === '6ad6d5243ac2699868136ad5' && !u.pathname.includes('/object/'))
check('Navigate here sets the free destination', true)
// museum details page and its object modal slot still work after the route-group move
await page.goto(base + '/en/museum/6ad6d5253ac2699868136b04')
await page.getByRole('link', { name: 'View details' }).first().click()
await page.getByRole('dialog').waitFor()
check('museum page object modal (@object slot) still works', await page.getByRole('dialog').isVisible())
check('no page errors', errors.length === 0, errors.join(' | '))
await browser.close(); console.log(failures ? failures + ' FAILED' : 'ALL PASSED')
